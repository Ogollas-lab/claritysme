import type { FinancialRecord, KPISnapshot, Company, Currency } from "@/types";
import { formatCurrency, formatPct } from "@/lib/calculations/kpi";

function escapeCSV(val: string | number | null | undefined): string {
	if (val === null || val === undefined) return "";
	const value = String(val);
	return value.includes(",") || value.includes('"') || value.includes("\n")
		? `"${value.replace(/"/g, '""')}"`
		: value;
}

function row(...cells: (string | number | null | undefined)[]): string {
	return cells.map(escapeCSV).join(",");
}

export function exportRecordsToCSV(records: FinancialRecord[], company: Company): string {
	void company;
	const header = row("date", "description", "type", "category", "amount", "currency", "source", "period_month", "period_year");
	const lines = records.map((record) => row(record.date, record.description, record.type, record.category, record.amount, record.currency, record.source, record.period_month, record.period_year));
	return [header, ...lines].join("\n");
}

export function exportSnapshotsToCSV(snapshots: KPISnapshot[], currency: Currency): string {
	void currency;
	const header = row("period", "total_revenue", "recurring_revenue", "total_cogs", "gross_profit", "gross_margin_pct", "total_opex", "total_payroll", "payroll_ratio_pct", "ebitda", "net_profit", "net_margin_pct", "cash_balance", "burn_rate", "runway_months", "revenue_per_employee", "mom_revenue_growth_pct", "mrr", "arr");
	const lines = snapshots.map((snapshot) => row(`${snapshot.period_year}-${String(snapshot.period_month).padStart(2, "0")}`, snapshot.total_revenue, snapshot.recurring_revenue, snapshot.total_cogs, snapshot.gross_profit, snapshot.gross_margin_pct, snapshot.total_opex, snapshot.total_payroll, snapshot.payroll_ratio_pct, snapshot.ebitda, snapshot.net_profit, snapshot.net_margin_pct, snapshot.cash_balance, snapshot.burn_rate, snapshot.runway_months ?? "", snapshot.revenue_per_employee, snapshot.mom_revenue_growth_pct ?? "", snapshot.mrr ?? "", snapshot.arr ?? ""));
	return [header, ...lines].join("\n");
}

export function downloadFile(content: string, filename: string, mimeType = "text/csv;charset=utf-8;"): void {
	if (typeof window === "undefined") return;
	const blob = new Blob([content], { type: mimeType });
	const url = URL.createObjectURL(blob);
	const link = document.createElement("a");
	link.setAttribute("href", url);
	link.setAttribute("download", filename);
	document.body.appendChild(link);
	link.click();
	document.body.removeChild(link);
	URL.revokeObjectURL(url);
}

export function downloadRecordsCSV(records: FinancialRecord[], company: Company): void {
	const date = new Date().toISOString().slice(0, 10);
	downloadFile(exportRecordsToCSV(records, company), `${company.name.replace(/\s+/g, "-")}-transactions-${date}.csv`);
}

export function generateTextSummary(snapshot: KPISnapshot, company: Company): string {
	const format = (value: number) => formatCurrency(value, company.currency);
	const period = new Date(snapshot.period_year, snapshot.period_month - 1).toLocaleDateString("en", { month: "long", year: "numeric" });
	return `FINANCIAL SUMMARY — ${company.name.toUpperCase()}
Period: ${period}
Generated: ${new Date().toLocaleString("en")}
${"=".repeat(50)}

REVENUE & PROFITABILITY
	Total Revenue:       ${format(snapshot.total_revenue)}
	Recurring Revenue:   ${format(snapshot.recurring_revenue)}
	Gross Profit:        ${format(snapshot.gross_profit)} (${formatPct(snapshot.gross_margin_pct)} margin)
	EBITDA:              ${format(snapshot.ebitda)} (${formatPct(snapshot.ebitda_margin_pct)} margin)
	Net Profit:          ${format(snapshot.net_profit)}

COSTS
	Cost of Goods Sold:  ${format(snapshot.total_cogs)}
	Operating Expenses:  ${format(snapshot.total_opex)}
	Payroll:             ${format(snapshot.total_payroll)} (${formatPct(snapshot.payroll_ratio_pct)} of revenue)

CASH POSITION
	Cash Balance:        ${format(snapshot.cash_balance)}
	Burn Rate:           ${snapshot.burn_rate <= 0 ? `+${format(Math.abs(snapshot.burn_rate))} surplus` : `${format(snapshot.burn_rate)}/mo`}
	Runway:              ${snapshot.runway_months !== null ? `${snapshot.runway_months.toFixed(1)} months` : "N/A (profitable)"}

EFFICIENCY
	Revenue/Employee:    ${format(snapshot.revenue_per_employee)}/mo
	MoM Revenue Growth:  ${snapshot.mom_revenue_growth_pct !== null ? `${snapshot.mom_revenue_growth_pct > 0 ? "+" : ""}${snapshot.mom_revenue_growth_pct.toFixed(1)}%` : "N/A"}
${snapshot.mrr ? `  MRR:                 ${format(snapshot.mrr)}\n  ARR:                 ${format(snapshot.arr ?? 0)}` : ""}

Generated by ClaritySME — claritysme.io
`;
}
